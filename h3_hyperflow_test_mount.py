def sha256_of(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(8 * 1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def find_dataset_root(slug):
    if not KAGGLE_INPUT.exists():
        return None
    dirs = [d for d in KAGGLE_INPUT.iterdir() if d.is_dir()]
    for d in dirs:
        if d.name == slug:
            return d
    for d in dirs:
        if slug in d.name:
            return d
    return None


def locate_mount_file(root, subpath):
    """Find a model file by its models/-relative path; fall back to a
    recursive basename search (mount layout may nest the subtree)."""
    base = subpath.rsplit("/", 1)[-1]
    if root is not None:
        direct = root / subpath
        if direct.is_file():
            return direct
        for cand in sorted(root.rglob(base)):
            if cand.is_file():
                return cand
    if KAGGLE_INPUT.exists():
        for cand in sorted(KAGGLE_INPUT.rglob(base)):
            if cand.is_file():
                return cand
    return None


def kaggle_input_inventory(max_entries=200):
    if not KAGGLE_INPUT.exists():
        return ["<no /kaggle/input directory>"]
    entries = []
    for p in sorted(KAGGLE_INPUT.rglob("*")):
        if len(entries) >= max_entries:
            entries.append("... (inventory truncated)")
            break
        rel = p.relative_to(KAGGLE_INPUT)
        if p.is_dir():
            entries.append(f"{rel}/")
        elif p.is_file():
            try:
                entries.append(f"{rel} ({p.stat().st_size} bytes)")
            except OSError:
                entries.append(f"{rel} (stat failed)")
    return entries


def phase_mount_check():
    """Runs BEFORE install: missing datasets must fail fast (FAIL_MOUNT)."""
    with Phase("MOUNT"):
        roots = {k: find_dataset_root(s) for k, s in DATASET_SLUGS.items()}
        for k, s in DATASET_SLUGS.items():
            log(f"dataset {s}: mount root = {roots[k]}")
        missing = []
        for key, subpath, required, approx in EXPECTED_MOUNT_FILES:
            p = locate_mount_file(roots.get(key), subpath)
            if p is None:
                if required:
                    missing.append(subpath)
                else:
                    note(f"optional mount file absent (ok): {subpath}")
                continue
            MOUNT_FOUND[subpath] = p
            size = p.stat().st_size
            log(f"mount: {subpath} -> {p} ({size / 2**30:.2f} GiB)")
            if approx and size < approx * 0.5:
                note(f"mounted file {subpath} is suspiciously small: "
                     f"{size} bytes vs expected ~{approx}")
        if missing:
            inventory = kaggle_input_inventory()
            log("FAIL_MOUNT — missing required model files: " + ", ".join(missing))
            write_result("FAIL_MOUNT", {
                "failed_phase": "MOUNT",
                "error": f"missing mounted model files: {missing}",
                "missing_files": missing,
                "kaggle_input_inventory": inventory,
            })
            print(json.dumps({"verdict": "FAIL_MOUNT", "missing_files": missing},
                             indent=2), flush=True)
            sys.exit(1)
        note("models supplied by Kaggle dataset mounts (no HF download in this variant)")


def phase_link_models():
    """Symlink the mounted files into ComfyUI's models/ layout."""
    with Phase("MODELS"):
        models_root = COMFY / "models"
        for key, subpath, required, approx in EXPECTED_MOUNT_FILES:
            src = MOUNT_FOUND.get(subpath)
            if src is None:
                continue  # optional + absent (already noted in MOUNT phase)
            dest = models_root / subpath
            dest.parent.mkdir(parents=True, exist_ok=True)
            if dest.is_symlink() or dest.exists():
                dest.unlink()
            os.symlink(src, dest)
            log(f"link {dest} -> {src}")
        up = MOUNT_FOUND.get(UPSCALER_MODELS_PATH)
        if up is not None:
            dest2 = models_root / UPSCALER_SECOND_PATH
            dest2.parent.mkdir(parents=True, exist_ok=True)
            if dest2.is_symlink() or dest2.exists():
                dest2.unlink()
            os.symlink(up, dest2)
            log(f"link {dest2} -> {up} (upscaler second location)")
            got = sha256_of(up)
            if got != UPSCALER_SHA256:
                raise RuntimeError(f"SHA-256 mismatch for mounted upscaler: {got}")
            log("  SHA-256 verified through mount: upscaler")


