def log(msg):
    print(f"[{time.strftime('%H:%M:%S')}] {msg}", flush=True)


def note(msg):
    STATE["notes"].append(msg)
    log("NOTE: " + msg)


class Phase:
    def __init__(self, name):
        self.name = name

    def __enter__(self):
        CURRENT_PHASE[0] = self.name
        self.t0 = time.time()
        log(f"===== PHASE {self.name} =====")
        return self

    def __exit__(self, *exc):
        dt = time.time() - self.t0
        STATE["phases"][self.name] = round(dt, 2)
        log(f"===== PHASE {self.name} done in {dt:.1f}s =====")
        return False


def run_cmd(cmd, cwd=None):
    log("$ " + " ".join(str(c) for c in cmd) + (f"   (cwd={cwd})" if cwd else ""))
    subprocess.run([str(c) for c in cmd], cwd=cwd, check=True)


def tail(path, n=80):
    try:
        lines = Path(path).read_text(errors="replace").splitlines()
        return "\n".join(lines[-n:])
    except Exception:
        return "<no log available>"


def http_json(method, path, payload=None, timeout=60):
    data = json.dumps(payload).encode() if payload is not None else None
    req = urllib.request.Request(SERVER_URL + path, data=data, method=method,
                                 headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return json.loads(r.read().decode())


def write_result(verdict, extra=None):
    result = {
        "verdict": verdict,
        "gpu_name": STATE["gpu_name"],
        "runs_seconds": STATE["runs_seconds"],
        "runs_wall_seconds": STATE["runs_wall_seconds"],
        "output_specs": STATE["output_specs"],
        "outputs": STATE["outputs"],
        "phase_timings": STATE["phases"],
        "prompt_variant": STATE["variant"],
        "notes": STATE["notes"],
    }
    if extra:
        result.update(extra)
    WORKING.mkdir(parents=True, exist_ok=True)
    (WORKING / "result.json").write_text(json.dumps(result, indent=2, ensure_ascii=False))
    log(f"result.json written: verdict={verdict}")
    return result


def stop_server():
    global SERVER_PROC
    if SERVER_PROC is not None and SERVER_PROC.poll() is None:
        SERVER_PROC.terminate()
        try:
            SERVER_PROC.wait(timeout=30)
        except subprocess.TimeoutExpired:
            SERVER_PROC.kill()
    SERVER_PROC = None


def fail(verdict, err):
    """Write a failure result.json (with ComfyUI log tail) and exit non-zero."""
    log(f"FAILURE in phase {CURRENT_PHASE[0]}: {err}")
    traceback.print_exc()
    write_result(verdict, {
        "failed_phase": CURRENT_PHASE[0],
        "error": str(err),
        "comfyui_log_tail": tail(SERVER_LOG, 80),
    })
    stop_server()
    print(json.dumps({"verdict": verdict, "failed_phase": CURRENT_PHASE[0],
                      "error": str(err)}, indent=2), flush=True)
    sys.exit(1)


