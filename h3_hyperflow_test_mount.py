class PromptRejected(Exception):
    pass


class RunFailed(Exception):
    def __init__(self, entry):
        self.entry = entry
        self.node_id = None
        self.detail = ""
        for ev, data in entry.get("status", {}).get("messages", []):
            if ev == "execution_error":
                self.node_id = str(data.get("node_id"))
                self.detail = f"{data.get('exception_type')}: {data.get('exception_message')}"
        super().__init__(f"execution_error at node {self.node_id}: {self.detail}")


def drop_nodes(prompt, ids):
    """Remove nodes `ids` and any inputs that referenced them."""
    out = {}
    for nid, node in prompt.items():
        if nid in ids:
            continue
        ins = {k: v for k, v in node["inputs"].items()
               if not (isinstance(v, list) and str(v[0]) in ids)}
        out[nid] = {"class_type": node["class_type"], "inputs": ins}
    return out


def build_submission_prompt(api_prompt):
    """Apply UI execution semantics (see module docstring); returns prompt dict."""
    prompt = json.loads(json.dumps(api_prompt))  # deep copy
    stripped = [nid for nid, n in prompt.items() if n["class_type"] in FRONTEND_ONLY_TYPES]
    for nid in stripped:
        del prompt[nid]
    if stripped:
        note(f"removed frontend-only note node(s) {stripped} before /prompt (inert, not executable)")
    if any(nid in prompt for nid in BYPASSED_NODE_IDS):
        prompt = drop_nodes(prompt, BYPASSED_NODE_IDS)
        note(f"applied UI bypass semantics: removed bypassed node(s) {sorted(BYPASSED_NODE_IDS)} "
             f"and inputs referencing them (node 75 ref_audios.ref_audio_0)")
    return prompt


def run_once(prompt, run_idx):
    """Submit prompt, poll history, return (entry, exec_seconds, wall_seconds)."""
    try:
        resp = http_json("POST", "/prompt",
                         {"prompt": prompt, "client_id": str(uuid.uuid4())}, timeout=120)
    except urllib.error.HTTPError as e:
        raise PromptRejected(e.read().decode("utf-8", "replace"))
    if resp.get("node_errors"):
        raise PromptRejected(json.dumps(resp["node_errors"], ensure_ascii=False))
    prompt_id = resp["prompt_id"]
    log(f"run {run_idx}: prompt_id={prompt_id}")
    t0 = time.time()
    while time.time() - t0 < RUN_TIMEOUT_S:
        if SERVER_PROC is not None and SERVER_PROC.poll() is not None:
            raise RuntimeError(f"ComfyUI server died during run {run_idx}; log tail:\n{tail(SERVER_LOG, 60)}")
        hist = http_json("GET", f"/history/{prompt_id}", timeout=60)
        if prompt_id in hist:
            entry = hist[prompt_id]
            st = entry.get("status", {})
            if st.get("status_str") == "error":
                raise RunFailed(entry)
            if st.get("completed") or st.get("status_str") == "success":
                start = succ = None
                for ev, data in st.get("messages", []):
                    if ev == "execution_start":
                        start = data.get("timestamp")
                    elif ev == "execution_success":
                        succ = data.get("timestamp")
                exec_s = (succ - start) / 1000.0 if start and succ else None
                return entry, exec_s, time.time() - t0
        time.sleep(15)
    raise TimeoutError(f"run {run_idx} exceeded {RUN_TIMEOUT_S}s")


def error_mentions_empty_loadimage(err):
    text = str(err)
    node_id = getattr(err, "node_id", None)
    if node_id in EMPTY_LOADIMAGE_IDS:
        return True
    return any(f'"{nid}"' in text or f"'{nid}'" in text for nid in EMPTY_LOADIMAGE_IDS)


def probe_mp4(path):
    """Return {width, height, frames, has_audio} via ffprobe, else PyAV, else {}."""
    ffprobe = shutil.which("ffprobe")
    if ffprobe:
        try:
            out = subprocess.run(
                [ffprobe, "-v", "error", "-show_entries",
                 "stream=codec_type,width,height,nb_frames", "-of", "json", str(path)],
                capture_output=True, text=True, timeout=120)
            streams = json.loads(out.stdout).get("streams", [])
            spec = {"has_audio": any(s.get("codec_type") == "audio" for s in streams)}
            for s in streams:
                if s.get("codec_type") == "video":
                    spec["width"], spec["height"] = s.get("width"), s.get("height")
                    nf = s.get("nb_frames")
                    spec["frames"] = int(nf) if str(nf).isdigit() else None
            return spec
        except Exception as e:
            log(f"ffprobe failed ({e}); falling back")
    try:
        import av
        with av.open(str(path)) as container:
            spec = {"has_audio": len(container.streams.audio) > 0}
            if container.streams.video:
                vs = container.streams.video[0]
                spec.update({"width": vs.width, "height": vs.height,
                             "frames": vs.frames or None})
            return spec
    except Exception as e:
        note(f"could not probe {path.name} (no ffprobe/PyAV): {e}")
        return {"file_size": path.stat().st_size}


def phase_runs(api_prompt):
    with Phase("RUNS"):
        prompt = build_submission_prompt(api_prompt)
        for run_idx in (1, 2, 3):
            if run_idx > 1:
                # Restart the server between runs: ComfyUI caches node outputs
                # across prompts in one session, which would make runs 2/3
                # measure the cache instead of the generation.
                log(f"restarting ComfyUI before run {run_idx} (defeat cross-prompt node cache)")
                stop_server()
                start_server()
            try:
                entry, exec_s, wall_s = run_once(prompt, run_idx)
            except (PromptRejected, RunFailed) as e:
                if run_idx == 1 and STATE["variant"] == "full" and error_mentions_empty_loadimage(e):
                    note(f"faithful prompt failed on empty LoadImage slot(s): {e}. "
                         f"Retrying run 1 without nodes {sorted(EMPTY_LOADIMAGE_IDS)} "
                         f"(and their ref_image_3/4/5 inputs).")
                    prompt = drop_nodes(prompt, EMPTY_LOADIMAGE_IDS)
                    STATE["variant"] = "no-empty-loadimage"
                    entry, exec_s, wall_s = run_once(prompt, run_idx)
                else:
                    raise
            STATE["runs_seconds"].append(round(exec_s, 2) if exec_s else None)
            STATE["runs_wall_seconds"].append(round(wall_s, 2))
            log(f"run {run_idx}: execution={exec_s:.1f}s wall={wall_s:.1f}s"
                if exec_s else f"run {run_idx}: wall={wall_s:.1f}s (no history timestamps)")
            # collect + copy outputs of node 83 (VHS_VideoCombine)
            gifs = (entry.get("outputs", {}).get("83", {}) or {}).get("gifs", [])
            for g in gifs:
                src = COMFY / "output" / g.get("subfolder", "") / g["filename"]
                if src.exists():
                    dst = WORKING / f"h3_hyperflow_r{run_idx}.mp4"
                    WORKING.mkdir(parents=True, exist_ok=True)
                    shutil.copyfile(src, dst)
                    STATE["outputs"].append(str(dst))
                    STATE["output_specs"].append(probe_mp4(src))
                    log(f"run {run_idx} output: {src} -> {dst} specs={STATE['output_specs'][-1]}")
                else:
                    note(f"run {run_idx}: output file not found at {src}")


